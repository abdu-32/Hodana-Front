export function sortCategoriesByDisplayOrder(categories: KBCategory[]): KBCategory[] {
  return [...categories].sort((a, b) => {
    const idxA = MASTER_CATEGORY_SLUG_ORDER.indexOf(a.slug);
    const idxB = MASTER_CATEGORY_SLUG_ORDER.indexOf(b.slug);
    const orderA = idxA !== -1 ? idxA : a.sortOrder || 999;
    const orderB = idxB !== -1 ? idxB : b.sortOrder || 999;
    return orderA - orderB;
  });
}

